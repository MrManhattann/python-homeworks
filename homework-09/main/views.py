
from django.shortcuts import render


def show_section(request, title, description, items=None, links=None):
    context = {
        "city_name": "Вінниця",
        "title": title,
        "description": description,
        "items": items or [],
        "links": links or [],
    }

    return render(request, "main/section.html", context)


